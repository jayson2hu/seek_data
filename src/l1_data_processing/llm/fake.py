from __future__ import annotations

import hashlib
from collections import defaultdict
from copy import deepcopy
from typing import Any

from l1_data_processing.llm.client import LLMResponse


class FakeLLM:
    def __init__(self, preset_responses: dict[str, dict[str, Any]] | None = None, embedding_dimensions: int = 8) -> None:
        self.preset_responses = preset_responses or {}
        self.embedding_dimensions = embedding_dimensions
        self.calls: dict[str, int] = defaultdict(int)

    def complete(self, prompt: str, *, model: str) -> LLMResponse:
        self.calls["complete"] += 1
        text = self.preset_responses.get("complete", {}).get("text", "fake completion")
        return LLMResponse(text=text, data={}, prompt_tokens=len(prompt.split()), completion_tokens=len(text.split()), model=model)

    def structured(self, prompt: str, *, schema_name: str, model: str) -> LLMResponse:
        self.calls["structured"] += 1
        self.calls[f"structured:{schema_name}"] += 1
        default = {
            "one_liner": "Deterministic L1 base analysis",
            "summary": "A deterministic summary generated by FakeLLM for standalone L1 validation.",
            "key_points": ["stub content loaded", "fake llm used", "base schema produced"],
            "quotes": [],
            "entities": ["L1"],
            "base_tags": ["data-processing", "standalone"],
        }
        defaults_by_schema: dict[str, dict[str, Any]] = {
            "BaseAnalysis": default,
            "ChunkAnalysis": default,
            "ContentFilter": {"ignore": False, "reason": "", "value": "normal"},
        }
        data = self.preset_responses.get(schema_name, defaults_by_schema.get(schema_name, default))
        if isinstance(data, list):
            index = self.calls[f"structured:{schema_name}"] - 1
            data = data[min(index, len(data) - 1)]
        data = deepcopy(data)
        return LLMResponse(
            text="",
            data=data,
            prompt_tokens=len(prompt.split()),
            completion_tokens=sum(len(str(value).split()) for value in data.values()),
            model=model,
        )

    def embed(self, text: str, *, model: str) -> list[float]:
        self.calls["embed"] += 1
        digest = hashlib.sha256(f"{model}:{text}".encode("utf-8")).digest()
        return [round(byte / 255, 6) for byte in digest[: self.embedding_dimensions]]
